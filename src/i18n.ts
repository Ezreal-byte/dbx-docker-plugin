export type I18nDict = typeof zh;

const dicts: Record<Locale, I18nDict> = { 'zh-CN': zh, en };

export function setLocale(raw: string | undefined) {
  locale.value = raw && raw.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function t(path: string, vars?: Record<string, string | number>): string {
  const dict = dicts[locale.value] as Record<string, unknown>;
  let value: unknown = dict;
  for (const part of path.split('.')) {
    if (value && typeof value === 'object') value = (value as Record<string, unknown>)[part];
    else { value = undefined; break; }
  }
  let text = typeof value === 'string' ? value : path;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}
